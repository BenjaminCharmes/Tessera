"""Export of the backend OpenAPI schema to a versioned file — ticket-684.

The frontend contract tests read ``docs/openapi.json`` instead of a running
backend. The file is regenerated by::

    cd backend && uv run python -m tessera.openapi_export          # rewrite
    cd backend && uv run python -m tessera.openapi_export --check  # exit 1 if stale

A backend test runs the check, so a route change that forgets the export fails
before it reaches a review.
"""
import json
import sys
from pathlib import Path

#: ``backend/src/tessera/openapi_export.py`` -> repository root.
SCHEMA_PATH = Path(__file__).resolve().parents[3] / "docs" / "openapi.json"


#: Dicts printed one entry per line; everything below them stays on one line,
#: so a changed route or model shows as one changed line and the file stays short.
_EXPANDED: frozenset[tuple[str, ...]] = frozenset(
    {(), ("components",), ("components", "schemas"), ("paths",)}
)


def _dump(value: object, path: tuple[str, ...] = ()) -> str:
    """Stable JSON: sorted keys, expanded down to routes and models only."""
    if not isinstance(value, dict) or path not in _EXPANDED:
        return json.dumps(value, sort_keys=True, ensure_ascii=False)
    indent = "  " * (len(path) + 1)
    lines = [
        f"{indent}{json.dumps(key, ensure_ascii=False)}: {_dump(value[key], (*path, key))}"
        for key in sorted(value)
    ]
    return "{\n" + ",\n".join(lines) + "\n" + "  " * len(path) + "}"


def render_schema() -> str:
    """The app schema, one line per route and per model, final newline."""
    from tessera.main import app

    return _dump(app.openapi()) + "\n"


def is_up_to_date(path: Path = SCHEMA_PATH) -> bool:
    """True when ``path`` holds exactly what the app serves today."""
    try:
        return path.read_text(encoding="utf-8") == render_schema()
    except FileNotFoundError:
        return False


def write_schema(path: Path = SCHEMA_PATH) -> None:
    """Rewrite ``path`` with the current schema."""
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(render_schema(), encoding="utf-8", newline="\n")


def main(argv: list[str], path: Path = SCHEMA_PATH) -> int:
    """Entry point: ``--check`` reports staleness, no argument rewrites the file."""
    if argv == ["--check"]:
        if is_up_to_date(path):
            return 0
        sys.stderr.write(
            f"{path} is stale: run `uv run python -m tessera.openapi_export`.\n"
        )
        return 1
    if argv:
        sys.stderr.write("usage: python -m tessera.openapi_export [--check]\n")
        return 2
    write_schema(path)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
